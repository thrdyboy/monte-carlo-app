// src/components/PlotsGallery.tsx
import { useState } from "react";
import type { LatestPlotsResponse, PlotItem } from "../types/api";
import solarCell from "../assets/Solar_Cells.png";

// ─────────────────────────────────────────────────────────────────────
// Inline metadata — human-friendly titles for each plot filename
// ─────────────────────────────────────────────────────────────────────

const PLOT_META: Record<string, { title: string; description: string }> = {
    "mc_time_series.png": {
        title: "Historical vs Forecast Rainfall",
        description:
            "Monthly rainfall: the historical record (blue) flows into a Monte Carlo forecast (red).",
    },
    "mc_heatmap.png": {
        title: "Forecast Rainfall Heatmap",
        description:
            "A single sampled Monte Carlo year, showing realistic intra-year patterns.",
    },
    "mc_heatmap_combined.png": {
        title: "Historical + Forecast Heatmap",
        description:
            "The full record: observed years plus the forecast window, month by month.",
    },
    "runoff_ts.png": {
        title: "Rainfall & Runoff",
        description:
            "SCS-CN runoff derived from forecast rainfall, month by month.",
    },
    "runoff_monthly.png": {
        title: "Average Monthly Pattern",
        description:
            "Mean rainfall vs mean runoff across the forecast window.",
    },
    "runoff_discharge.png": {
        title: "Average Monthly Discharge",
        description:
            "Basin discharge in m³/s, derived from runoff volume and basin area.",
    },
    "runoff_yearly.png": {
        title: "Yearly Totals",
        description:
            "Total rainfall vs total runoff per year in the forecast window.",
    },
};

function describePlot(name: string) {
    return (
        PLOT_META[name] ?? {
            title: name.replace(/\.png$/i, "").replace(/_/g, " "),
            description: "",
        }
    );
}

function formatBytes(bytes: number | null | undefined): string {
    if (bytes == null || bytes < 0) return "—";
    if (bytes < 1024) return `${bytes} B`;
    const kb = bytes / 1024;
    if (kb < 1024) return `${kb.toFixed(1)} KB`;
    return `${(kb / 1024).toFixed(2)} MB`;
}

// ─────────────────────────────────────────────────────────────────────
// Main gallery
// ─────────────────────────────────────────────────────────────────────

interface Props {
    data: LatestPlotsResponse | null;
}

export default function PlotsGallery({ data }: Props) {
    const [zoom, setZoom] = useState<PlotItem | null>(null);

    if (!data || data.plots.length === 0) {
        return (
            <div className="bg-white border border-slate-200 rounded-xl p-10 text-center text-slate-400 text-sm">
                No plots available.
            </div>
        );
    }

    // Split into two groups by prefix
    const monteCarlo = data.plots.filter((p) => p.name.startsWith("mc_"));
    const runoff = data.plots.filter((p) => p.name.startsWith("runoff_"));
    const others = data.plots.filter(
        (p) => !p.name.startsWith("mc_") && !p.name.startsWith("runoff_")
    );

    return (
        <>
            <div className="bg-white border border-slate-200 rounded-xl overflow-hidden">
                {/* ── Hero: solar cell intro ── */}
                <div className="grid grid-cols-1 md:grid-cols-2 border-b border-slate-100">
                    <div className="bg-slate-50 flex items-center justify-center p-6">
                        <img
                            src={solarCell}
                            alt="Solar cell reference"
                            className="max-h-80 w-auto object-contain"
                        />
                    </div>
                    <div className="p-6 flex flex-col justify-center">
                        <h3 className="text-lg font-semibold text-slate-800">
                            Monte Carlo Forecast Output
                        </h3>
                        <p className="text-sm text-slate-500 mt-2 leading-relaxed">
                            Visualisations generated by the ETL pipeline. Historical rainfall
                            feeds a Monte Carlo simulation which drives the SCS-CN runoff
                            model. All plots below are produced for the selected run.
                        </p>
                        <div className="mt-4 flex items-center gap-4 text-xs text-slate-400">
                            <span>{data.count} images</span>
                            <span>·</span>
                            <span className="font-mono truncate max-w-50">
                                {data.run_id}
                            </span>
                        </div>
                    </div>
                </div>

                {/* ── Monte Carlo section ── */}
                {monteCarlo.length > 0 && (
                    <PlotSection
                        title="Monte Carlo — Rainfall Forecast"
                        subtitle="Sampled distributions and the historical record"
                        plots={monteCarlo}
                        onZoom={setZoom}
                    />
                )}

                {/* ── Runoff section ── */}
                {runoff.length > 0 && (
                    <PlotSection
                        title="SCS-CN Runoff"
                        subtitle="Runoff, discharge, and yearly summaries"
                        plots={runoff}
                        onZoom={setZoom}
                    />
                )}

                {/* ── Anything else ── */}
                {others.length > 0 && (
                    <PlotSection
                        title="Other"
                        subtitle=""
                        plots={others}
                        onZoom={setZoom}
                    />
                )}
            </div>

            {/* ── Lightbox ── */}
            {zoom && (
                <div
                    className="fixed inset-0 z-50 bg-slate-900/85 backdrop-blur-sm flex items-center justify-center p-4"
                    onClick={() => setZoom(null)}
                >
                    <div
                        className="relative max-w-[95vw] max-h-[95vh]"
                        onClick={(e) => e.stopPropagation()}
                    >
                        <button
                            onClick={() => setZoom(null)}
                            aria-label="Close"
                            className="absolute -top-9 right-0 text-white/80 hover:text-white text-sm"
                        >
                            Close ✕
                        </button>
                        <img
                            src={zoom.view_url}
                            alt={zoom.name}
                            className="max-w-[95vw] max-h-[95vh] rounded-lg shadow-2xl bg-white"
                        />
                    </div>
                </div>
            )}
        </>
    );
}

// ─────────────────────────────────────────────────────────────────────
// Section (one grouped block of plots)
// ─────────────────────────────────────────────────────────────────────

function PlotSection({
    title,
    subtitle,
    plots,
    onZoom,
}: {
    title: string;
    subtitle: string;
    plots: PlotItem[];
    onZoom: (p: PlotItem) => void;
}) {
    // First plot is featured (spans full width) if there are more than 2
    const featured = plots.length > 2;

    return (
        <section className="px-6 py-6 border-b border-slate-100 last:border-b-0">
            <div className="mb-4">
                <h4 className="text-xs font-semibold uppercase tracking-wider text-slate-500">
                    {title}
                </h4>
                {subtitle && (
                    <p className="text-xs text-slate-400 mt-1">{subtitle}</p>
                )}
            </div>

            <div className="grid grid-cols-1 lg:grid-cols-2 gap-5">
                {plots.map((p, i) => (
                    <PlotCard
                        key={p.id}
                        plot={p}
                        featured={featured && i === 0}
                        onZoom={() => onZoom(p)}
                    />
                ))}
            </div>
        </section>
    );
}

// ─────────────────────────────────────────────────────────────────────
// Card (one plot)
// ─────────────────────────────────────────────────────────────────────

function PlotCard({
    plot,
    featured,
    onZoom,
}: {
    plot: PlotItem;
    featured: boolean;
    onZoom: () => void;
}) {
    const meta = describePlot(plot.name);

    return (
        <figure
            className={[
                "group rounded-lg border border-slate-200 overflow-hidden bg-white",
                "hover:border-indigo-300 hover:shadow-md transition-all",
                featured ? "lg:col-span-2" : "",
            ].join(" ")}
        >
            {/* Image with fixed aspect ratio → all plots look consistent */}
            <button
                onClick={onZoom}
                className={[
                    "block w-full bg-slate-50 cursor-zoom-in",
                    featured ? "aspect-16/7" : "aspect-16/10",
                ].join(" ")}
            >
                <img
                    src={plot.view_url}
                    alt={plot.name}
                    loading="lazy"
                    className="w-full h-full object-contain"
                />
            </button>

            {/* Caption */}
            <figcaption className="px-4 py-3 flex items-start justify-between gap-3 border-t border-slate-100">
                <div className="min-w-0">
                    <p className="text-sm font-medium text-slate-800 truncate">
                        {meta.title}
                    </p>
                    {meta.description && (
                        <p className="text-xs text-slate-500 mt-0.5">{meta.description}</p>
                    )}
                    <p className="text-[11px] text-slate-400 mt-1">
                        {formatBytes(plot.size_bytes)} · {plot.name}
                    </p>
                </div>

                <a
                    href={plot.download_url}
                    download
                    onClick={(e) => e.stopPropagation()}
                    className="text-xs text-indigo-600 hover:text-indigo-800 shrink-0 mt-1"
                >
                    Download
                </a>
            </figcaption>
        </figure>
    );
}